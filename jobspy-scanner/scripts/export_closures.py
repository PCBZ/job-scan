"""Writes the holidays library's NYSE closures for the Node app (#212).

Both apps decide trading days from one source: the scanner calls `holidays` at
run time, and the Node app reads this module's output,
functions/src/lib/nyse-closures.ts. tests/test_market_days.py fails when that
file differs from what the pinned `holidays` gives, so after bumping it, run:

    python -m scripts.export_closures
"""

from __future__ import annotations

import json
from datetime import date
from pathlib import Path

import holidays

from scanner.market_days import market_holidays

FIRST_YEAR, LAST_YEAR = 2020, 2060
NODE_MODULE = Path(__file__).resolve().parents[2] / "functions" / "src" / "lib" / "nyse-closures.ts"


def render() -> str:
    closures: dict[date, str] = {}
    for year in range(FIRST_YEAR, LAST_YEAR + 1):
        closures.update(market_holidays(year))
    rows = "".join(f"  {json.dumps(d.isoformat())}: {json.dumps(n)},\n" for d, n in sorted(closures.items()))
    return (
        f"// Generated by jobspy-scanner/scripts/export_closures.py from holidays=={holidays.__version__}:\n"
        "// NYSE's closures, date to name, as the scanner reads them at run time (#212). Don't edit.\n"
        "\n"
        f"export const FIRST_YEAR = {FIRST_YEAR};\n"
        f"export const LAST_YEAR = {LAST_YEAR};\n"
        "\n"
        "export const NYSE_CLOSURES: Readonly<Record<string, string>> = {\n"
        f"{rows}"
        "};\n"
    )


if __name__ == "__main__":
    NODE_MODULE.write_text(render())
